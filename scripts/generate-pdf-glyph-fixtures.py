#!/usr/bin/env python3
"""Generate tiny original fonts for PDF glyph validation; development-only fontTools."""
import base64
import io
import json
from pathlib import Path

import fontTools
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib.tables._g_l_y_f import Glyph, GlyphComponent
from fontTools.ttLib import TTCollection, TTFont
from fontTools.ttLib.tables._c_m_a_p import CmapSubtable


def font(cyclic):
    builder = FontBuilder(1000, isTTF=True)
    builder.setupGlyphOrder([".notdef", "A"])
    empty = TTGlyphPen(None).glyph()
    if cyclic:
        glyph = Glyph()
        glyph.numberOfContours = -1
        component = GlyphComponent()
        component.glyphName, component.x, component.y, component.flags = "A", 0, 0, 2
        glyph.components = [component]
    else:
        pen = TTGlyphPen(None)
        pen.moveTo((0, 0))
        pen.lineTo((500, 0))
        pen.lineTo((250, 500))
        pen.closePath()
        glyph = pen.glyph()
    for item in [empty, glyph]:
        item.xMin, item.yMin, item.xMax, item.yMax = 0, 0, 500, 500
    builder.setupGlyf({".notdef": empty, "A": glyph}, calcGlyphBounds=False)
    builder.setupHorizontalMetrics({".notdef": (500, 0), "A": (500, 0)})
    builder.setupHorizontalHeader(ascent=800, descent=-200)
    builder.setupCharacterMap({65: "A"})
    builder.setupNameTable({"familyName": "Aide Synthetic Glyph", "styleName": "Regular", "uniqueFontIdentifier": "AideSynthetic1", "fullName": "Aide Synthetic Glyph", "psName": "AideSyntheticGlyph"})
    builder.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200)
    builder.setupPost()
    builder.setupMaxp()
    builder.font.recalcBBoxes = False
    builder.font.recalcTimestamp = False
    builder.font["head"].created = builder.font["head"].modified = 3865536000
    output = io.BytesIO()
    builder.save(output)
    return base64.b64encode(output.getvalue()).decode()


if __name__ == "__main__":
    output = {"provenance": f"Original two-glyph triangle/self-component fonts generated by this script with fontTools {fontTools.version}; no system/third-party font bytes.", "normal": font(False), "cyclic": font(True)}
    normal = base64.b64decode(output["normal"])
    collection = TTCollection()
    collection.fonts = [TTFont(io.BytesIO(normal), recalcTimestamp=False)]
    data = io.BytesIO()
    collection.save(data)
    output["collection"] = base64.b64encode(data.getvalue()).decode()
    unicode_font = TTFont(io.BytesIO(normal), recalcTimestamp=False)
    table = CmapSubtable.newSubtable(12)
    table.platformID, table.platEncID, table.language = 3, 1, 0
    table.cmap = {65: "A"}
    unicode_font["cmap"].tables = [table]
    data = io.BytesIO()
    unicode_font.save(data)
    output["format12"] = base64.b64encode(data.getvalue()).decode()
    destination = Path(__file__).resolve().parent / "fixtures/pdf-ttf-glyphs.json"
    destination.write_text(json.dumps(output, indent=2) + "\n", encoding="utf-8")
