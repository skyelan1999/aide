func officePreviewTestInput(t *testing.T) []byte {
	t.Helper()
	var b bytes.Buffer
	z := zip.NewWriter(&b)
	f, _ := z.Create("xl/workbook.xml")
	f.Write([]byte(`<workbook/>`))
	z.Close()
	return b.Bytes()
}

func TestOfficePreviewIdentityCacheAndLimits(t *testing.T) {
	a := testApp(t)
	old := officePreviewConvert
	officePreviewCache.Lock()
	officePreviewCache.keys = nil
	officePreviewCache.values = map[string]officePreviewResult{}
	officePreviewCache.Unlock()
	defer func() { officePreviewConvert = old }()
	calls := 0
	officePreviewConvert = func(ctx context.Context, b []byte, ext string) (officePreviewResult, error) {
		calls++
		return officePreviewResult{PDF: []byte("%PDF-1.4\nfixture"), Meta: []byte(`{"pages":1,"sheets":[]}`)}, nil
	}
	input := officePreviewTestInput(t)
	dwgWrite(t, a, "book.xlsx", input)
	for _, format := range []string{"pdf", "meta", "pdf"} {
		w := request(a, "GET", "/api/office/preview?path=book.xlsx&format="+format, nil)
		if w.Code != 200 || w.Header().Get("Cache-Control") != "no-store" {
			t.Fatal(w.Code, w.Body.String())
		}
	}
	if calls != 1 {
		t.Fatal("same content not cached", calls)
	}
	after, _ := a.workspace.ReadFile("book.xlsx")
	if !bytes.Equal(input, after) {
		t.Fatal("source modified")
	}
	w := httptest.NewRecorder()
	a.Handler().ServeHTTP(w, httptest.NewRequest("GET", "/api/office/preview?path=book.xlsx&format=pdf", nil))
	if w.Code != 401 {
		t.Fatal("unauthorized cache read", w.Code)
	}
	for _, q := range []string{"path=../book.xlsx&format=pdf", "path=book.docx&format=pdf", "path=book.xlsx&format=other", "path=book.xlsx&format=page&page=0&size=1024", "path=book.xlsx&format=page&page=1&size=4097"} {
		if w := request(a, "GET", "/api/office/preview?"+q, nil); w.Code != 400 {
			t.Fatal(q, w.Code)
		}
	}
	os.Symlink("book.xlsx", filepath.Join(a.workPath, "link.xlsx"))
	if w := request(a, "GET", "/api/office/preview?path=link.xlsx&format=pdf", nil); w.Code != 400 {
		t.Fatal("symlink accepted", w.Code)
	}
	dwgWrite(t, a, "bad.ppt", []byte("not a compound file"))
	if w := request(a, "GET", "/api/office/preview?path=bad.ppt&format=pdf", nil); w.Code != 400 {
		t.Fatal(w.Code)
	}
	officePreviewSlots <- struct{}{}
	officePreviewSlots <- struct{}{}
	w = request(a, "GET", "/api/office/preview?path=book.xlsx&format=pdf", nil)
	<-officePreviewSlots
	<-officePreviewSlots
	if w.Code != 429 {
		t.Fatal("unbounded conversions", w.Code)
	}
	// A content hit does not grant access after a source is disabled.
	dir := a.reference.Name()
	os.WriteFile(filepath.Join(dir, "ref.xlsx"), input, 0600)
	a.sourceRegistry.Sources = append(a.sourceRegistry.Sources, Source{ID: "office-preview-ref", Name: "Preview", Type: "local", Enabled: true, RW: false})
	u := "/api/office/preview?path=ref.xlsx&source=office-preview-ref&format=pdf"
	if w := request(a, "GET", u, nil); w.Code != 200 {
		t.Fatal(w.Code, w.Body.String())
	}
	a.mu.Lock()
	a.sourceRegistry.Sources[len(a.sourceRegistry.Sources)-1].Enabled = false
	a.mu.Unlock()
	if w := request(a, "GET", u, nil); w.Code == 200 {
		t.Fatal("disabled source got cached bytes")
	}
	// A source change during conversion must discard even successfully generated bytes.
	dwgWrite(t, a, "other.xlsx", append(input, 1))
	officePreviewConvert = func(ctx context.Context, b []byte, ext string) (officePreviewResult, error) {
		a.mu.Lock()
		a.wsRevision++
		a.mu.Unlock()
		return officePreviewResult{PDF: []byte("%PDF-old"), Meta: []byte(`{"pages":1}`)}, nil
	}
	if w := request(a, "GET", "/api/office/preview?path=other.xlsx&format=pdf", nil); w.Code != 409 {
		t.Fatal("stale output accepted", w.Code, w.Body.String())
	}
}

func TestOfficePreviewConverterCancellation(t *testing.T) {
	dir := t.TempDir()
	script := "#!/bin/sh\nsleep 30\n"
	os.WriteFile(filepath.Join(dir, "soffice"), []byte(script), 0700)
	t.Setenv("PATH", dir+":"+os.Getenv("PATH"))
	ctx, cancel := context.WithTimeout(context.Background(), 150*time.Millisecond)
	defer cancel()
	start := time.Now()
	_, err := convertOfficePreview(ctx, officePreviewTestInput(t), ".xlsx")
	if err == nil || time.Since(start) > 4*time.Second {
		t.Fatal("converter not cancelled", err)
	}
}

func TestOfficePreviewRealRenderer(t *testing.T) {
	if os.Getenv("AIDE_OFFICE_PREVIEW_REAL") != "1" {
		t.Skip("requires candidate Office renderer")
	}
	for _, kind := range []string{"xlsx", "pptx"} {
		spec := map[string]any{"slides": []any{map[string]any{"title": "Preview 预览", "body": "Line one\n第二行"}}}
		if kind == "xlsx" {
			spec = map[string]any{"sheets": []any{map[string]any{"name": "数据", "rows": []any{[]any{"标题", "Line one\n第二行"}, []any{"数值", 42}}}}}
		}
		input, err := officeCreateBytes(kind, spec)
		if err != nil {
			t.Fatal(err)
		}
		ctx, cancel := context.WithTimeout(context.Background(), 70*time.Second)
		out, err := convertOfficePreview(ctx, input, "."+kind)
		cancel()
		if err != nil || !bytes.HasPrefix(out.PDF, []byte("%PDF-")) || !strings.Contains(string(out.Meta), `"pages": 1`) {
			t.Fatal(kind, err, string(out.Meta))
		}
	}
}
