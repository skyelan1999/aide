package server

import (
	"context"
	"crypto/sha256"
	"encoding/json"
	"errors"
	"net/http"
	"time"
)

// All mutable fields are guarded by App.mu. Instances are parent-only, never sent to the frame.
type pluginWorkbenchBridge struct {
	Ticket      pluginWorkbenchTicket
	Revision    uint64
	Package     string
	Expires     time.Time
	Ready, Busy bool
	Seen        map[string]bool
	Proposals   map[string]string // task -> session, only proposals generated by this instance
	Cancel      context.CancelFunc
}

func (a *App) workbenchBridgeLocked(id, key string, full bool) (*pluginWorkbenchBridge, error) {
	b := a.pluginWorkbenchBridges[key]
	if b == nil || b.Ticket.ID != id || !b.Ready || time.Now().After(b.Expires) {
		return nil, errors.New("workbench instance expired")
	}
	lock := a.loadLockStateLocked()
	if lock.Locked || lock.Gen != b.Ticket.Gen || a.wsRevision != b.Revision || a.managementBaseLocked("plugins", id) != b.Ticket.Base {
		return nil, errors.New("workbench scope revoked")
	}
	enabled := false
	for _, p := range a.pluginRegistry.Plugins {
		if p.ID == id && p.Enabled && p.Workbench != nil {
			enabled = true
			break
		}
	}
	if !enabled {
		return nil, errors.New("plugin disabled")
	}
	if full {
		page, err := a.workbenchPageLocked(id)
		if err != nil || sha256.Sum256(page) != b.Ticket.Digest || a.pluginPackageDigestLocked(id) != b.Package {
			return nil, errors.New("plugin changed; reopen workbench")
		}
	}
	return b, nil
}
func (a *App) closeWorkbenchBridge(w http.ResponseWriter, r *http.Request) {
	a.mu.Lock()
	defer a.mu.Unlock()
	key := r.PathValue("instance")
	if b := a.pluginWorkbenchBridges[key]; b != nil && b.Ticket.ID == r.PathValue("id") {
		if b.Cancel != nil {
			b.Cancel()
		}
		delete(a.pluginWorkbenchBridges, key)
	}
	jsonOut(w, 200, map[string]bool{"ok": true})
}

type workbenchBridgeRequest struct {
	Protocol    int            `json:"protocol"`
	RequestID   string         `json:"requestId"`
	Method      string         `json:"method"`
	Tool        string         `json:"tool"`
	Arguments   map[string]any `json:"arguments"`
	Attachments []Attachment   `json:"attachments,omitempty"`
	ProposalID  string         `json:"proposalId,omitempty"`
}

func (a *App) callWorkbenchBridge(w http.ResponseWriter, r *http.Request) {
	var req workbenchBridgeRequest
	if err := decode(w, r, &req); err != nil {
		fail(w, 400, err)
		return
	}
	if req.Protocol != 1 || !workbenchNamePattern.MatchString(req.RequestID) || len(req.Attachments) > 16 {
		fail(w, 400, errors.New("invalid bridge request"))
		return
	}
	id, key := r.PathValue("id"), r.PathValue("instance")
	a.mu.Lock()
	b, err := a.workbenchBridgeLocked(id, key, true)
	if err != nil {
		a.mu.Unlock()
		fail(w, 403, err)
		return
	}
	if req.Method == "proposal.status" {
		sessionID := b.Proposals[req.ProposalID]
		s := a.sessions[sessionID]
		var result map[string]any
		if s != nil && !s.Deleted {
			for _, t := range s.Runs {
				if t.ID == req.ProposalID {
					result = map[string]any{"sessionId": s.ID, "proposalId": t.ID, "status": t.Status, "applied": t.Applied}
					break
				}
			}
		}
		a.mu.Unlock()
		if result == nil {
			fail(w, 404, errors.New("proposal not owned by this workbench"))
			return
		}
		jsonOut(w, 200, map[string]any{"requestId": req.RequestID, "status": "result", "result": result})
		return
	}
	allowed := false
	for _, p := range a.pluginRegistry.Plugins {
		if p.ID == id && p.Workbench != nil {
			for _, tool := range p.Workbench.Tools {
				if req.Tool == tool {
					allowed = true
				}
			}
		}
	}
	if req.Method != "tool.call" || !allowed || id == "browser-control" || id == "computer-control" || !pluginPlanArgumentsAllowed(req.Arguments) {
		a.mu.Unlock()
		fail(w, 403, errors.New("tool not permitted by workbench"))
		return
	}
	if b.Busy || b.Seen[req.RequestID] || len(b.Seen) >= 128 {
		a.mu.Unlock()
		fail(w, 409, errors.New("busy, replayed or exhausted workbench request"))
		return
	}
	b.Seen[req.RequestID] = true
	b.Busy = true
	ctx, cancel := context.WithTimeout(r.Context(), 310*time.Second)
	b.Cancel = cancel
	task := &Task{ID: newID(), Status: "running", Created: time.Now().UTC().Format(time.RFC3339Nano), Prompt: "Plugin workbench tool: " + req.Tool, WorkspaceID: a.wsID(), WorkspaceRev: a.wsRevision, WorkspaceMode: a.workspaceMode(), WorkspaceRemotePath: a.wsConfig.Workspace.Path, Attachments: req.Attachments, AutoReview: false}
	scope, workspace, epoch := a.pluginsPath, a.workPath, a.wsRevision
	a.mu.Unlock()
	defer func() {
		cancel()
		a.mu.Lock()
		if a.pluginWorkbenchBridges[key] == b {
			b.Busy = false
			b.Cancel = nil
		}
		a.mu.Unlock()
	}()
	admission := func() error {
		a.mu.Lock()
		_, e := a.workbenchBridgeLocked(id, key, false)
		a.mu.Unlock()
		if e != nil {
			return e
		}
		return a.pluginPlanPolicy(task, req.Tool, id, scope, workspace, epoch)
	}
	if err = admission(); err != nil {
		fail(w, 403, err)
		return
	}
	// Resource admission reruns exactly the existing plugin plan policy after queue waits.
	ctx = context.WithValue(ctx, pluginPlanAdmissionKey{}, admission)
	done := make(chan struct{})
	defer close(done)
	go func() {
		ticker := time.NewTicker(200 * time.Millisecond)
		defer ticker.Stop()
		for {
			select {
			case <-done:
				return
			case <-ctx.Done():
				return
			case <-ticker.C:
				if admission() != nil {
					cancel()
					return
				}
			}
		}
	}()
	a.filesMu.Lock()
	_, _, versions, err := a.attachmentContext(req.Attachments)
	a.filesMu.Unlock()
	if err != nil {
		fail(w, 400, err)
		return
	}
	raw, err := a.callPluginToolContext(ctx, id, req.Tool, req.Arguments)
	if err != nil {
		fail(w, 400, err)
		return
	}
	if ctx.Err() != nil {
		fail(w, 409, errors.New("call cancelled; verify external effects before retry"))
		return
	}
	a.filesMu.Lock()
	defer a.filesMu.Unlock()
	a.mu.Lock()
	_, err = a.workbenchBridgeLocked(id, key, true)
	a.mu.Unlock()
	if err != nil {
		fail(w, 409, err)
		return
	}
	text, proposals := normalizePluginResult(raw)
	for _, prop := range proposals {
		if _, err = a.recordToolProposal(task, versions, prop); err != nil {
			fail(w, 400, err)
			return
		}
	}
	encoded, err := json.Marshal(raw)
	if err != nil || len(encoded) > 2<<20 {
		fail(w, 400, errors.New("tool result exceeds bridge limit"))
		return
	}
	response := map[string]any{"requestId": req.RequestID, "status": "result", "result": raw}
	if len(task.Files) > 0 || len(task.Commands) > 0 {
		task.Status = "awaiting_approval"
		task.Steps = []Step{{Name: "Plugin workbench", Status: "done", Content: text}}
		now := time.Now().UTC().Format(time.RFC3339Nano)
		s := &Session{ID: newID(), Title: "Plugin workbench: " + id, Created: now, Updated: now, Runs: []*Task{task}}
		a.mu.Lock()
		_, err = a.workbenchBridgeLocked(id, key, false)
		if err == nil {
			a.assignSessionNumber(s)
			a.sessions[s.ID] = s
			err = a.save(s)
			if err == nil {
				b.Proposals[task.ID] = s.ID
			} else {
				delete(a.sessions, s.ID)
			}
		}
		a.mu.Unlock()
		if err != nil {
			fail(w, 500, err)
			return
		}
		response["status"] = "proposal_pending"
		response["proposalId"] = task.ID
		response["sessionId"] = s.ID
		a.broadcastSessionsChanged(s.ID)
	}
	jsonOut(w, 200, response)
}
